/// Closed: solid black (blends with the hardware notch). Open: Liquid Glass with a black scrim
/// whose opacity follows `glassIntensity`, plus a top fade so the hardware-notch band melts into the glass.
/// The backdrop is composited by WindowServer (no screen capture, no per-frame CPU work) and only
/// exists while the notch is open and glass is enabled.
private struct NotchBackground: View {
    let isOpen: Bool
    let shape: NotchShape
    let notchHeight: CGFloat

    /// Distance over which the black hardware-notch band melts into the glass.
    private let fadeLength: CGFloat = 70

    @Default(.glassIntensity) private var glassIntensity
    @Environment(\.accessibilityReduceTransparency) private var reduceTransparency
    @Environment(\.colorSchemeContrast) private var contrast

    var body: some View {
        if !isOpen || glassIntensity <= 0 || reduceTransparency {
            Color.black
        } else {
            // Contrast floor: glass never gets fully clear behind text (higher with Increase Contrast).
            let minScrim = contrast == .increased ? 0.6 : 0.12
            let scrim = 1 - glassIntensity * (1 - minScrim)
            ZStack(alignment: .top) {
                glass
                // One single dimming layer: black under the hardware notch, eased down to `scrim`,
                // then flat. No overlapping layers, so no visible seam.
                VStack(spacing: 0) {
                    LinearGradient(stops: fadeStops(scrim: scrim), startPoint: .top, endPoint: .bottom)
                        .frame(height: notchHeight + fadeLength)
                    Color.black.opacity(scrim)
                }
            }
            .environment(\.colorScheme, .dark)
        }
    }

    /// Solid black over the notch height, then a smoothstep ease to `scrim` (sampled, avoids Mach bands).
    private func fadeStops(scrim: Double) -> [Gradient.Stop] {
        let total = notchHeight + fadeLength
        let start = notchHeight / total
        var stops: [Gradient.Stop] = [.init(color: .black, location: 0), .init(color: .black, location: start)]
        let steps = 10
        for i in 1...steps {
            let t = Double(i) / Double(steps)
            let eased = t * t * (3 - 2 * t)
            stops.append(.init(color: .black.opacity(1 - eased * (1 - scrim)), location: start + (1 - start) * t))
        }
        return stops
    }

    @ViewBuilder private var glass: some View {
        if #available(macOS 26.0, *) {
            // Above 80% use the clearer glass variant: more of the screen below shows through.
            Color.clear.glassEffect(glassIntensity > 0.8 ? .clear : .regular, in: shape)
        } else {
            VisualEffectView(material: .hudWindow, blendingMode: .behindWindow)
        }
    }
}
